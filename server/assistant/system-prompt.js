export const buildInventoryAssistantContext = ({ date, products, entries }) => ({
  date,
  products: products.slice(0, 500).map((product) => ({
    id: product.id,
    name: product.name,
    unit: product.unit,
    category: product.category,
  })),
  reportEntries: entries.map((entry) => ({
    productId: entry.product_id,
    name: entry.name,
    unit: entry.unit,
    arrival: entry.arrival,
    remainder: entry.remainder,
    writeOff: entry.write_off,
  })),
})
